import { snowflakeClient } from "../../../../../infrastructure/snowflake/snowflake.client";
import { PaginationResponseDto } from "../../../../../shared/dto/pagination-response.dto";
import type { DashboardDataSource } from "../dashboard.datasource";

export class SnowflakeDashboardDataSourceImpl implements DashboardDataSource {
  async getSalesActivity(
    page: number,
    limit: number,
  ): Promise<PaginationResponseDto<Record<string, unknown>>> {
    const baseQuery = `
      SELECT
        ACTIVITY_DETAIL.TASK_ID,
        ACTIVITY_DETAIL.TASK_CREATED_AT,
        ACTIVITY_DETAIL.TASK_PLANNED_DATE,
        ACTIVITY_DETAIL.TASK_STATUS,
        ACTIVITY_DETAIL.VISIT_TYPE,
        ACTIVITY_DETAIL.VISIT_REMARKS,
        ACTIVITY_DETAIL.CHECK_IN_DATE,
        ACTIVITY_DETAIL.CHECK_OUT_DATE,
        ACTIVITY_DETAIL.VISIT_DURATION,

        ACTIVITY_DETAIL.SALES_EMPLOYEE_ID,
        ACTIVITY_DETAIL.SALES_EMPLOYEE_CODE,
        ACTIVITY_DETAIL.SALES_EMPLOYEE_DESC,

        ACTIVITY_DETAIL.CUSTOMER_ID,
        ACTIVITY_DETAIL.CUSTOMER_EXTERNAL_ID,
        ACTIVITY_DETAIL.CUSTOMER_NAME,
        ACTIVITY_DETAIL.STORE_NAME,
        ACTIVITY_DETAIL.CUSTOMER_TYPE,

        ACTIVITY_DETAIL.ACTIVITY_ID,
        ACTIVITY_DETAIL.ACTIVITY_TYPE,
        ACTIVITY_DETAIL.ACTIVITY_DESC,

        ACTIVITY_DETAIL.BUSINESS_SEGMENT_CODE,
        ACTIVITY_DETAIL.BUSINESS_SEGMENT_DESC,

        ACTIVITY_DETAIL.ACTIVITY_FORM_ID,
        ACTIVITY_DETAIL.FORM_ID,
        ACTIVITY_DETAIL.FORM_KEY,
        ACTIVITY_DETAIL.FORM_NAME,
        ACTIVITY_DETAIL.HAS_FORM_RESPONSE,
        ACTIVITY_DETAIL.FORM_RESPONSE_ID,

        ACTIVITY_DETAIL.FIELD_KEY,
        ACTIVITY_DETAIL.FIELD_NAME,
        ACTIVITY_DETAIL.FIELD_LABEL,
        ACTIVITY_DETAIL.FIELD_VALUE,

        EMPLOYEE.SALES_UPLINE_ID,
        EMPLOYEE.SALES_UPLINE_CODE,
        EMPLOYEE.SALES_UPLINE_DESC,
        EMPLOYEE.SALES_ROLE_DESC,
        EMPLOYEE.TARGET_LEADS,
        EMPLOYEE.TARGET_OUTLET,
        EMPLOYEE.TARGET_VISIT,

        EMPLOYEE.CREATED_AT AS EMPLOYEE_CREATED_AT,
        EMPLOYEE.CREATED_BY AS EMPLOYEE_CREATED_BY,
        EMPLOYEE.UPDATED_AT AS EMPLOYEE_UPDATED_AT,
        EMPLOYEE.UPDATED_BY AS EMPLOYEE_UPDATED_BY,
        EMPLOYEE.DELETED_AT AS EMPLOYEE_DELETED_AT,
        EMPLOYEE.DELETED_BY AS EMPLOYEE_DELETED_BY,
        EMPLOYEE.IS_DELETED AS EMPLOYEE_IS_DELETED,

        CUSTOMER.SALES_ID,
        CUSTOMER.CUSTOMER_ADDRESS,
        CUSTOMER.CUSTOMER_REMARKS,
        CUSTOMER.CUSTOMER_LEAD_STATUS,
        CUSTOMER.CUSTOMER_STATUS,
        CUSTOMER.CUSTOMER_PRIORITY,
        CUSTOMER.CUSTOMER_SINCE,
        CUSTOMER.CUSTOMER_QUALIFIED_SINCE,

        CUSTOMER.CREATED_AT AS CUSTOMER_CREATED_AT,
        CUSTOMER.CREATED_BY AS CUSTOMER_CREATED_BY,
        CUSTOMER.UPDATED_AT AS CUSTOMER_UPDATED_AT,
        CUSTOMER.UPDATED_BY AS CUSTOMER_UPDATED_BY,
        CUSTOMER.DELETED_AT AS CUSTOMER_DELETED_AT,
        CUSTOMER.DELETED_BY AS CUSTOMER_DELETED_BY,
        CUSTOMER.IS_DELETED AS CUSTOMER_IS_DELETED

      FROM PROD_DB.DSTR_BI_COMMUNITY.F_SALES_PRESALES_ACTIVITY_DETAIL AS ACTIVITY_DETAIL

      LEFT JOIN PROD_DB.DSTR_BI_COMMUNITY.D_SALES_PRESALES_EMPLOYEE AS EMPLOYEE
        ON ACTIVITY_DETAIL.SALES_EMPLOYEE_ID = EMPLOYEE.SALES_EMPLOYEE_ID

      LEFT JOIN PROD_DB.DSTR_BI_COMMUNITY.D_SALES_PRESALES_CUSTOMER AS CUSTOMER
        ON ACTIVITY_DETAIL.CUSTOMER_ID = CUSTOMER.CUSTOMER_ID
    `;

    const countQuery = `SELECT COUNT(*) AS total FROM (${baseQuery}) AS sales_activity`;
    const totalRows = await snowflakeClient.query<{ TOTAL: number }>(countQuery);
    const total = Number(totalRows[0]?.TOTAL ?? 0);

    const paginatedQuery = `
      ${baseQuery}
      LIMIT ${limit} OFFSET ${(page - 1) * limit}
    `;

    const rows = await snowflakeClient.query<Record<string, unknown>>(paginatedQuery);

    return PaginationResponseDto.from(rows, page, limit, total);
  }
}
